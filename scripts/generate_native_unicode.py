"""Regenerate native name-normalization properties from the supported Python Unicode data."""

import unicodedata
from collections.abc import Callable
from pathlib import Path


def ranges(predicate: Callable[[str], bool]) -> list[int]:
    result = []
    start = None
    for codepoint in range(0x110001):
        included = codepoint < 0x110000 and predicate(chr(codepoint))
        if included and start is None:
            start = codepoint
        elif not included and start is not None:
            result.extend((start, codepoint - 1))
            start = None
    return result


def main() -> None:
    lines = [
        '"""Generated by scripts/generate_native_unicode.py; do not edit by hand."""',
        "",
        "from std.utils import StaticTuple",
        "",
        f'comptime UNICODE_VERSION = "{unicodedata.unidata_version}"',
        "",
        "def _contains[T: Int](codepoint: Int, bounds: StaticTuple[Int, T]) -> Bool:",
        "    var low = 0",
        "    var high = T // 2",
        "    while low < high:",
        "        var mid = (low + high) // 2",
        "        if codepoint < bounds[mid * 2]:",
        "            high = mid",
        "        elif codepoint > bounds[mid * 2 + 1]:",
        "            low = mid + 1",
        "        else:",
        "            return True",
        "    return False",
        "",
    ]
    for name, predicate in [("alnum", str.isalnum), ("digit", str.isdigit), ("space", str.isspace)]:
        bounds = ranges(predicate)
        lines += [f"comptime _{name.upper()} = StaticTuple[Int, {len(bounds)}]("]
        lines += [
            "    " + ", ".join(hex(x) for x in bounds[i : i + 12]) + ","
            for i in range(0, len(bounds), 12)
        ]
        lines += [
            ")",
            "",
            f"def is_{name}(codepoint: Int) -> Bool:",
            f"    return _contains(codepoint, _{name.upper()})",
            "",
        ]
    (Path(__file__).resolve().parents[1] / "mojo/mojo_bindgen/_unicode.mojo").write_text(
        "\n".join(lines)
    )


if __name__ == "__main__":
    main()
